/* GET /api/feed — the auto-post feed for the PEOnomics LinkedIn page (RSS 2.0).

   Reads data/post-schedule.json (GENERATED by tools/build_posts.py from data/posts/series.json)
   and lists only the posts whose go-live time has passed, newest first, within the last
   feedWindowDays. A post "goes live" just by its time arriving: no commit, no cron. Zapier's
   RSS trigger polls this URL and publishes each new item once (deduped by <guid>).

   GET /api/feed?audit=1 — plain-text weekly audit: what is live now and what goes live in the
   next 35 days, with the full post text. Nothing here takes input or touches personal data. */

const AUDIT_DAYS = 35;
const DAY = 86400000;

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&apos;');

export async function loadSchedule(request, env) {
  const url = new URL('/data/post-schedule.json', request.url);
  const res = env && env.ASSETS ? await env.ASSETS.fetch(new Request(url)) : await fetch(url);
  if (!res.ok) throw new Error('schedule ' + res.status);
  return res.json();
}

export function liveItems(sched, now) {
  const windowMs = (sched.meta.feedWindowDays || 21) * DAY;
  return sched.items
    .filter(it => { const t = Date.parse(it.liveAt); return t <= now && now - t < windowMs; })
    .sort((a, b) => Date.parse(b.liveAt) - Date.parse(a.liveAt));
}

export function upcomingItems(sched, now, days = AUDIT_DAYS) {
  return sched.items.filter(it => { const t = Date.parse(it.liveAt); return t > now && t - now <= days * DAY; });
}

export function rss(sched, items) {
  const ch = sched.meta.channel;
  const entry = it => [
    '<item>',
    `<title>${esc(it.headline)}</title>`,
    `<link>${esc(it.url)}</link>`,
    `<guid isPermaLink="false">${esc('peonomics-post-' + it.id)}</guid>`,
    `<pubDate>${esc(it.pubDate)}</pubDate>`,
    `<category>${esc(it.label)}</category>`,
    `<description>${esc(it.text)}</description>`,
    `<enclosure url="${esc(it.image)}" type="image/png" length="${Number(it.imageBytes) || 0}"/>`,
    `<media:content url="${esc(it.image)}" medium="image" type="image/png" width="1200" height="627"/>`,
    '</item>'
  ].join('');
  return '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<rss version="2.0" xmlns:media="http://search.yahoo.com/mrss/" xmlns:atom="http://www.w3.org/2005/Atom"><channel>' +
    `<title>${esc(ch.title)}</title><link>${esc(ch.link)}</link><description>${esc(ch.description)}</description>` +
    `<language>en-us</language><atom:link href="${esc(ch.link)}api/feed" rel="self" type="application/rss+xml"/>` +
    items.map(entry).join('') + '</channel></rss>\n';
}

export function audit(sched, now) {
  const fmt = it => `--- ${it.liveAt}  [${it.label}]  ${it.id}\nimage: ${it.image}\n\n${it.text}\n`;
  const live = liveItems(sched, now), next = upcomingItems(sched, now);
  return [
    `PEOnomics auto-post audit — ${new Date(now).toISOString()}`,
    `Data reviewed: ${Object.entries(sched.meta.dataVersions || {}).map(([k, v]) => `${k} ${v}`).join(', ')}`,
    `Dormant releases (set a date in data/posts/series.json to mark): ${(sched.meta.dormantReleases || []).join(', ') || 'none'}`,
    '', `LIVE IN FEED (${live.length})`, ...live.map(fmt),
    '', `GOING LIVE IN THE NEXT ${AUDIT_DAYS} DAYS (${next.length})`, ...next.map(fmt)
  ].join('\n');
}

export async function onRequestGet({ request, env }) {
  let sched;
  try { sched = await loadSchedule(request, env); }
  catch { return new Response('feed unavailable', { status: 503, headers: { 'cache-control': 'no-store' } }); }
  const now = Date.now();
  if (new URL(request.url).searchParams.get('audit') === '1') {
    return new Response(audit(sched, now), { headers: { 'content-type': 'text/plain; charset=utf-8', 'cache-control': 'no-store', 'x-robots-tag': 'noindex' } });
  }
  return new Response(rss(sched, liveItems(sched, now)), {
    headers: { 'content-type': 'application/rss+xml; charset=utf-8', 'cache-control': 'public, max-age=300', 'x-robots-tag': 'noindex' }
  });
}
